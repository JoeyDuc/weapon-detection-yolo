import { chromium } from '@playwright/test'
const browser = await chromium.launch({ headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 1100 }, deviceScaleFactor: 1 })
const errors = []
page.on('pageerror', error => errors.push(error.message))
await page.goto('http://127.0.0.1:5173/')
await page.waitForResponse(response => response.url().includes('/api/analytics/summary') && response.ok()).catch(() => {})
await page.waitForTimeout(500)
await page.screenshot({ path: '../docs/overview-desktop.png', fullPage: true })
await page.setViewportSize({ width: 390, height: 844 })
await page.waitForTimeout(500)
const mobileOverflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)
await page.screenshot({ path: '../docs/overview-mobile.png', fullPage: true })
await page.setViewportSize({ width: 1440, height: 1100 })
await page.goto('http://127.0.0.1:5173/settings')
await page.getByRole('button', { name: 'Dark', exact: true }).click()
await page.goto('http://127.0.0.1:5173/')
await page.waitForTimeout(500)
await page.screenshot({ path: '../docs/overview-dark.png', fullPage: true })
const summary = await page.request.get('http://127.0.0.1:5173/api/analytics/summary').then(r => r.json())
await page.goto('http://127.0.0.1:5173/settings')
await page.getByRole('button', { name: 'Light', exact: true }).click()
console.log(JSON.stringify({ errors, mobileOverflow, summary, title: await page.title() }))
await browser.close()
